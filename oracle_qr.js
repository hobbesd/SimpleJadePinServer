// Page logic of the Oracle QR page (oracle_qr.html): builds the
// "update_pinserver" QR code that points a Jade at this pin server.

"use strict";

function generate() {
    var urlA = document.getElementById("urla").value;
    var urlB = document.getElementById("urlb").value;
    var pubkey = document.getElementById("pubkey").value.trim();

    if (!pubkey) {
        alert("Please specify a pubkey");
        return;
    }

    // A compressed secp256k1 public key: 33 bytes, first byte 02 or 03.
    // Anything else would configure the Jade with a key no server has.
    if (!/^0[23][0-9a-fA-F]{64}$/.test(pubkey)) {
        alert("The pubkey must be 66 hex characters and start with 02 or 03");
        return;
    }

    pubkey = fromHexString(pubkey);

    var bcur = bcur_encode_single("jade-updps", {
        "id": "001",
        "method": "update_pinserver",
        "params": {
            "urlA": urlA,
            "urlB": urlB,
            "pubkey": pubkey
        }
    }).toUpperCase();

    var qr = qrcode(0, 'L');
    qr.addData(bcur, 'Alphanumeric');
    qr.make();
    // Markup generated by qrcode.js from our own encoder output (an <img>
    // with a data: URL)
    document.getElementById("generated_qrcode").innerHTML = qr.createImgTag(4);
    document.getElementById("qr_tile").hidden = false;
}

// Pre-fill urlA with the address this page was opened under
document.getElementById("urla").value = window.location.protocol + "//" + window.location.host;
document.getElementById("btn_generate").addEventListener("click", generate);
